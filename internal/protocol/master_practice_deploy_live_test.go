func TestParseMasterPracticeDeployInfo_Live20261126(t *testing.T) {
	raw, err := hex.DecodeString(masterPracticeDeployLive20261126Hex)
	if err != nil {
		t.Fatalf("解码黄金载荷失败: %v", err)
	}
	info, err := protocol.ParseMasterPracticeDeployInfoResult(raw)
	if err != nil {
		t.Fatalf("解析布阵信息失败: %v", err)
	}
	if info.Result != protocol.MasterPracticeResultSuccess {
		t.Fatalf("result = %d, want success", info.Result)
	}
	if info.DeployLevel != 20 {
		t.Fatalf("deploy_level = %d, want 20", info.DeployLevel)
	}
	if len(info.Roles) != 9 {
		t.Fatalf("roles = %d, want 9", len(info.Roles))
	}
	if len(info.Grids) != 11 {
		t.Fatalf("grids = %d, want 11", len(info.Grids))
	}
	first := info.Roles[0]
	if first.PlayerRoleID != 1216785 || first.RoleID != 806 || first.RoleName != "圣宇文拓" ||
		first.RoleLevel != 237 || first.IsDeploy != 0 {
		t.Fatalf("role[0] = %+v", first)
	}
	main := info.Roles[7]
	if main.PlayerRoleID != 227943 || main.IsMainRole != 1 || main.RoleID != 511 ||
		main.RoleName != "飞羽男天师" || main.RoleLevel != 300 || main.IsDeploy != 1 {
		t.Fatalf("role[7] = %+v", main)
	}
	if info.Grids[9].GridTypeID != 9 || info.Grids[9].PlayerRoleID != 1006659 {
		t.Fatalf("grid[9] = %+v", info.Grids[9])
	}
	if info.Grids[10].GridTypeID != 1 || info.Grids[10].PlayerRoleID != 227943 {
		t.Fatalf("grid[10] = %+v", info.Grids[10])
	}
}
