func mustHex(t *testing.T, hexs string) []byte {
	t.Helper()
	b := make([]byte, len(hexs)/2)
	for i := 0; i < len(b); i++ {
		var v uint8
		for j := 0; j < 2; j++ {
			c := hexs[i*2+j]
			switch {
			case c >= '0' && c <= '9':
				v = v*16 + c - '0'
			case c >= 'a' && c <= 'f':
				v = v*16 + c - 'a' + 10
			case c >= 'A' && c <= 'F':
				v = v*16 + c - 'A' + 10
			}
		}
		b[i] = v
	}
	return b
}

func TestParseMagicArrayPanel(t *testing.T) {
	p, err := protocol.ParseMagicArrayPanelResponse(mustHex(t, testPayload_magic))
	if err != nil {
		t.Fatalf("parse magic array: %v", err)
	}
	if p.Level != 16 || p.Exp != 9340 || p.MaxExp != 41000 {
		t.Fatalf("unexpected magic array: %+v", p)
	}
	var big *protocol.MagicArrayCostItem
	for i := range p.CostItems {
		if p.CostItems[i].ItemID == 6909 {
			big = &p.CostItems[i]
		}
	}
	if big == nil || big.AddExp != 500 {
		t.Fatalf("missing 大法力石 cost item: %+v", p.CostItems)
	}
}

func TestParseBloodlineInfo(t *testing.T) {
	p, err := protocol.ParseBloodlineInfoResponse(mustHex(t, testPayload_blood))
	if err != nil {
		t.Fatalf("parse bloodline: %v", err)
	}
	if len(p.Bloodlines) != 6 {
		t.Fatalf("expected 6 bloodlines, got %d", len(p.Bloodlines))
	}
	seen := map[int32]bool{}
	for _, b := range p.Bloodlines {
		seen[b.Level] = true
		if b.MainRoleLevel != 80 {
			t.Fatalf("expected main role level 80, got %+v", b)
		}
	}
	for _, lv := range []int32{80, 60, 31, 1} {
		if !seen[lv] {
			t.Fatalf("missing bloodline level %d in %+v", lv, p.Bloodlines)
		}
	}
}

